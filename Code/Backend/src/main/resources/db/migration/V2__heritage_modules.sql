CREATE TABLE supported_language (
    language_code VARCHAR(10) PRIMARY KEY,
    language_name VARCHAR(80) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

INSERT INTO supported_language (language_code, language_name) VALUES
    ('vi', 'Tiếng Việt'),
    ('en', 'English');

CREATE TABLE heritage_site (
    site_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(160) NOT NULL,
    description VARCHAR(10000) NOT NULL DEFAULT '',
    address VARCHAR(255) NOT NULL DEFAULT '',
    latitude DECIMAL(9, 6),
    longitude DECIMAL(9, 6),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE artifact (
    artifact_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id BIGINT NOT NULL REFERENCES heritage_site(site_id),
    code VARCHAR(50) NOT NULL UNIQUE,
    location_name VARCHAR(160) NOT NULL DEFAULT '',
    latitude DECIMAL(9, 6),
    longitude DECIMAL(9, 6),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE artifact_content (
    content_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artifact_id BIGINT NOT NULL REFERENCES artifact(artifact_id) ON DELETE CASCADE,
    language_code VARCHAR(10) NOT NULL REFERENCES supported_language(language_code),
    title VARCHAR(200) NOT NULL,
    description VARCHAR(10000) NOT NULL,
    image_url VARCHAR(1000),
    video_url VARCHAR(1000),
    audio_url VARCHAR(1000),
    CONSTRAINT uq_artifact_language UNIQUE (artifact_id, language_code)
);

CREATE TABLE beacon_device (
    beacon_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    beacon_uuid VARCHAR(36) NOT NULL,
    major INTEGER NOT NULL CHECK (major BETWEEN 0 AND 65535),
    minor INTEGER NOT NULL CHECK (minor BETWEEN 0 AND 65535),
    artifact_id BIGINT REFERENCES artifact(artifact_id) ON DELETE SET NULL,
    placement VARCHAR(255) NOT NULL DEFAULT '',
    latitude DECIMAL(9, 6),
    longitude DECIMAL(9, 6),
    tx_power INTEGER NOT NULL DEFAULT -59,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_beacon_identity UNIQUE (beacon_uuid, major, minor)
);

CREATE TABLE favorite (
    favorite_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    artifact_id BIGINT NOT NULL REFERENCES artifact(artifact_id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_favorite_user_artifact UNIQUE (user_id, artifact_id)
);

CREATE TABLE visitor_interaction (
    interaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_key VARCHAR(36) NOT NULL UNIQUE,
    user_id BIGINT NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    artifact_id BIGINT NOT NULL REFERENCES artifact(artifact_id),
    beacon_id BIGINT REFERENCES beacon_device(beacon_id),
    language_code VARCHAR(10) NOT NULL REFERENCES supported_language(language_code),
    duration_seconds INTEGER NOT NULL DEFAULT 0 CHECK (duration_seconds >= 0),
    happened_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_interaction_happened_at ON visitor_interaction(happened_at);
CREATE INDEX idx_interaction_artifact ON visitor_interaction(artifact_id);
CREATE INDEX idx_interaction_user ON visitor_interaction(user_id);

CREATE TABLE visitor_feedback (
    feedback_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    artifact_id BIGINT NOT NULL REFERENCES artifact(artifact_id) ON DELETE CASCADE,
    rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment VARCHAR(2000) NOT NULL DEFAULT '',
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_feedback_user_artifact UNIQUE (user_id, artifact_id)
);

CREATE TABLE revoked_token (
    token_id VARCHAR(36) PRIMARY KEY,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL
);
